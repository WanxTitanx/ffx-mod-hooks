#!/usr/bin/env python3
"""Generate the bounded Tarot symbol catalog from reviewed authored locations."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def location(point):
    room, x, z = point
    if not isinstance(room, int) or not 1 <= room <= 65535:
        raise ValueError("Invalid native room")
    if not all(isinstance(v, (int, float)) and math.isfinite(v) and abs(v) < 100000 for v in (x, z)):
        raise ValueError("Invalid authored ground-plane position")
    return "{%d,%.6ff,%.6ff}" % (room, x, z)


def main():
    source = ROOT / "research/mod_008_arcana/acquisition_sites.json"
    data = json.loads(source.read_text())
    if [row["card"] for row in data["sites"]] != list(range(78)):
        raise ValueError("Expected every stable card exactly once")
    lines = ["// Generated by research/mod_008_arcana/build_acquisition_catalog.py.",
             "// GPL-3.0: authored route anchors and provenance in acquisition_sites.json.",
             "#pragma once", "namespace FfxHooks::Arcana::Acquisition::Data {",
             "inline constexpr std::array<Site,kStandardCardCount> sites{{"]
    for row in data["sites"]:
        if not 0 <= row["stage"] < 25 or not row["hint"].isascii() or not row["evidence"]:
            raise ValueError("Missing stage, English hint or source evidence")
        lines.append(" {%d,%d,%s,%s}," % (row["card"], row["stage"], location(row["location"]), json.dumps(row["hint"])))
    lines.append("}};")
    for key in ("pyreflies", "ifritEmblems", "chocoboPosts"):
        values = data[key]
        if len(values) != 3 or len({tuple(point) for point in values}) != 3:
            raise ValueError("Every route needs three distinct marks")
        lines.append("inline constexpr std::array<Location,3> %s{{%s}};" % (key, ",".join(map(location, values))))
    lines.append("inline constexpr Location recovery=%s;" % location(data["recovery"]))
    lines += ["}", ""]
    (ROOT / "src/runtime/FfxHooksDll/hooks/ArcanaAcquisitionCatalog.generated.h").write_text("\n".join(lines))
    print("PASS: 78 authored Tarot sites, three bounded routes and one recovery symbol")


if __name__ == "__main__":
    main()
