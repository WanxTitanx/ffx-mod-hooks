struct Presentation {const std::uint8_t* text=nullptr;std::uint16_t model=0;};
inline bool Resolve(std::uint16_t name,std::uint8_t owner,bool alternateText,Presentation& out) noexcept {
    const unsigned index=name&0x0fffu;
    if(owner!=7||index>=Names.size())return false;
    // The upstream English catalog has no alternate reading. Preserve the
    // full name for both native text variants rather than inventing generic names.
    (void)alternateText;
    const bool armor=index>=74;
    const Presentation value{Names[index].data(),
                             static_cast<std::uint16_t>(armor?0x4067:0x4066)};
    out=value;return true;
}
