"""Jarvis-HOOK: generate public metadata only; never read or embed game assets."""
from pathlib import Path
import argparse
import csv
import io
import json

ROOT = Path(__file__).resolve().parents[2]
LEGACY = [
    (1, 1, "Opening Veil", "Haste, Protect and Shell on the first turn.", "Veil"),
    (2, 2, "Counter March", "Counterattack after taking a hit.", "March"),
    (3, 2, "Low HP Rush", "Gain Haste below half health.", "Rush"),
    (4, 1, "Ward Stack", "Shell, Regen, NulBlaze and NulShock at the opening.", "Ward"),
    (5, 2, "Frost-Flood Weave", "Blizzara and Watera pressure on the front line.", "Weave"),
    (6, 2, "Shoreline Break", "Watera against the front line.", "Break"),
    (7, 1, "Sin Salve", "Self-healing below half health.", "Salve"),
    (8, 2, "Mist Chorus", "White Wind for allied monsters below half health.", "Chorus"),
]

def validate(catalog):
    areas = {a["id"]: a for a in catalog["areas"]}
    curves = {c["id"]: c for c in catalog["curses"]}
    if catalog["schema"] != 2 or len(curves) != len(catalog["curses"]):
        raise ValueError("Invalid or duplicate curse identity")
    if set(curves) != set(range(9, 42)):
        raise ValueError("Expanded UNI identities must include the explicit UNI013B=41 mapping")
    fields = [f for a in areas.values() for f in a["fields"]]
    if len(fields) != len(set(fields)) or any(f in catalog["unavailableFields"] for f in fields):
        raise ValueError("A scripted-only field cannot become a natural area alias")
    seen = set()
    exclusive = {21: 186, 22: 66, 23: 64, 40: None}
    for m in catalog["monsters"]:
        identity = (m["area"], m["monster"])
        if identity in seen or m["area"] not in areas or not m["allowed"] or not m["fields"]:
            raise ValueError(f"Invalid monster entry: {identity}")
        seen.add(identity)
        if not set(m["fields"]) <= set(areas[m["area"]]["fields"]):
            raise ValueError("Monster field is outside its admitted area")
        for cid in m["allowed"]:
            if not 1 <= cid <= 41:
                raise ValueError("Curse mask exceeds its bounded identity domain")
            if cid in exclusive and (m["monster"] not in (198, 200) if cid == 40 else m["monster"] != exclusive[cid]):
                raise ValueError("A signature UNI was assigned to another monster")
            if cid in curves and curves[cid]["threat"] > areas[m["area"]]["maxThreat"]:
                raise ValueError("Curse exceeds its reviewed regional threat")
    if any(sum(m["area"] == a for m in catalog["monsters"]) > 64 for a in areas):
        raise ValueError("Area exceeds the bounded runtime roster capacity")
    return areas, curves

def render(catalog):
    areas, curves = validate(catalog)
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    text = ["#pragma once", "#include <array>", "#include <cstdint>",
            "// Jarvis-HOOK. Generated by tools/sin_profiles/generate_catalog.py.",
            "// Exact per-monster curation; no game bytecode or asset bytes are embedded.",
            "namespace FfxHooks::SinSpread {",
            "struct CurseEntry {unsigned id,threat;const char* name;const char* description;const char* shortName;};",
            "struct MonsterEntry {std::uint16_t id,field;std::uint64_t allowedMask;const char* name;};",
            "struct NaturalPair {std::uint16_t field,monster;};",
            "struct AreaAlias {std::uint16_t field,area;unsigned maxThreat;bool awakeningOnly;};",
            "struct AreaEntry {std::uint16_t id;const char* name;};",
            "inline constexpr CurseEntry kCurses[]={", '{0,0,"No curse","Original monster behavior and size.",""},']
    for cid, threat, name, description, short_name in LEGACY:
        text.append(f"{{{cid},{threat},{quote(name)},{quote(description)},{quote(short_name)}}},")
    for cid, c in sorted(curves.items()):
        skills = "; ".join(s["Name"] for s in c["skills"])
        description = "After the native action: " + (skills or ("replay its resolved command once." if c["replayNative"] else "Zombie only on party members who actually lost HP."))
        if c["forbiddenField"] == 42:
            description += "; separate ATEL Berserk side effect."
        text.append(f"{{{cid},{c['threat']},{quote(c['name'])},{quote(description)},{quote(c['shortName'])}}},")
    text += ["};", "inline constexpr unsigned kMaximumCurse=41;", "inline constexpr MonsterEntry kMonsters[]={"]
    for m in catalog["monsters"]:
        mask = sum(1 << (cid - 1) for cid in set(m["allowed"]))
        text.append(f"{{{m['monster']},{m['area']},0x{mask:X}ULL,{quote(m['name'])}}},")
    text += ["};", "inline constexpr NaturalPair kNaturalPairs[]={"]
    for field, monster in sorted((f, m["monster"]) for m in catalog["monsters"] for f in m["fields"]):
        text.append(f"{{{field},{monster}}},")
    text += ["};", "inline constexpr AreaAlias kAreaAliases[]={"]
    for area in areas.values():
        for field in area["fields"]:
            text.append(f"{{{field},{area['id']},{area['maxThreat']},{str(area.get('awakeningOnly',False)).lower()}}},")
    capacity = max(sum(m["area"] == a for m in catalog["monsters"]) for a in areas)
    text += ["};", "inline constexpr AreaEntry kAreas[]={"]
    text += [f"{{{a['id']},{quote(a['name'])}}}," for a in areas.values()]
    text += ["};", f"inline constexpr unsigned kMaximumAreaMonsters={capacity};", "} // namespace FfxHooks::SinSpread", ""]
    csv_text = io.StringIO(newline="")
    writer = csv.writer(csv_text, lineterminator="\n")
    writer.writerow(["area", "monster", "name", "role", "natural_fields", "allowed_presets", "rationale"])
    for m in catalog["monsters"]:
        ids = [curves[cid]["preset"] if cid in curves else f"UNI-{cid:03}" for cid in m["allowed"]]
        writer.writerow([areas[m["area"]]["name"], f"m{m['monster']:03}", m["name"], m["role"], "|".join(map(str, m["fields"])), "|".join(ids), m["reason"]])
    return {
        ROOT / "src/runtime/FfxHooksDll/hooks/SinSpreadCatalog.generated.h": "\n".join(text),
        ROOT / "docs/research/SIN_MONSTER_UNI_MATRIX_2026_10_03.csv": csv_text.getvalue(),
    }

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads((Path(__file__).parent / "catalog.json").read_text())
    for path, content in render(catalog).items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Stale generated metadata: {path}")
        else:
            path.write_text(content, newline="")
    print(f"SIN catalog: {len(catalog['monsters'])} area/monster entries; explicit exclusions and signature checks passed.")

if __name__ == "__main__":
    main()
