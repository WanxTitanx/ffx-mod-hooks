"""Generate the clean six-row Aero contract; inspect inputs without writing data."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

DONORS = (30, 30, 31, 32, 33, 97)


def bind(path):
    data = path.read_bytes()
    section, first, last, width = (struct.unpack_from('<H', data, p)[0] for p in (0, 8, 10, 12))
    start = struct.unpack_from('<I', data, 16)[0]
    if (section, first, width, start) != (1, 0, 108, 20) or last < 174 or start + (last+1)*108 > len(data):
        raise ValueError(f'Unexpected ability table: {path}')
    rows = []
    for effect, donor in enumerate(DONORS):
        # DATA's final v4 contract uses explicit UI metadata and no inherited
        # combat bytes. Locale donors are never copied.
        row = bytearray(92)
        if effect in (0, 2, 3, 4):
            row[{0: 1, 2: 4, 3: 3, 4: 2}[effect]] = 0x40
        if effect == 5:
            row[0] = 1
        row[88] = 20
        row[89] = 35 if effect < 2 else 36
        row[90] = (0, 0, 2, 3, 4, 1)[effect]
        rows.append(bytes(row))
    return rows, hashlib.sha256(data).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--ability', type=Path, action='append', required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--evidence', type=Path, required=True)
    a = p.parse_args()
    canonical, sources = None, []
    for path in a.ability:
        rows, checksum = bind(path)
        if canonical is not None and rows != canonical:
            raise ValueError(f'Aero contract differs: {path}')
        canonical = rows
        sources.append({'path': str(path.resolve()), 'sha256': checksum})
    text = '#pragma once\n// Generated by tools/aero_equipment/generate_payloads.py; only the six approved Aero payloads.\n#include <array>\nnamespace FfxHooks::AeroEquipment {\ninline constexpr std::array<std::array<unsigned char,92>,6> Payloads{{\n'
    text += ',\n'.join('    {{' + ','.join(f'0x{x:02X}' for x in row) + '}}' for row in canonical)
    text += '\n}};\n}\n'
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(text)
    a.evidence.parent.mkdir(parents=True, exist_ok=True)
    a.evidence.write_text(json.dumps({'donors': DONORS, 'sources': sources}, indent=2)+'\n')
    print(f'Bound six Aero payloads across {len(sources)} language banks; no game data written.')


if __name__ == '__main__':
    main()
