"""Generate immutable runtime floors; never edit ordinary monster files."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Same-family endgame references. Values come from the authored Spira Reforge
# Calm Lands/Gagazet monsters, before Difficulty and SIN; not from live actors.
FAMILIES = {
    5: [2, 3, 4], 14: [9, 11, 12, 13], 20: [16, 17, 18, 19, 79, 80, 81, 82, 209],
    34: [28, 29, 30, 32, 33], 8: [6, 7], 38: [35, 36, 37, 50],
    63: [23, 24, 25, 26, 27, 59, 60, 61, 62], 57: [44, 45, 55, 56],
    66: [181], 186: [185], 194: [193], 40: [214, 215],
    71: [68], 72: [69], 73: [70], 88: [87], 84: [46, 208, 217, 223],
    92: [91, 96, 198, 200], 98: [97],
}

def generate(mod: Path, receipt: Path, output: Path, evidence: Path):
    pairs={tuple(pair) for pair in json.loads(receipt.read_text())['naturalPairs']}
    fields={f for region in json.loads((ROOT/'tools/capture_cascade/catalog.json').read_text())['regions'] for f in region['fields']}
    # Noncapturable ordinary machina and Fallen Monks are not replacement slots,
    # but their existing curated natural SIN identities still need the stat floor.
    for entry in json.loads((ROOT/'tools/sin_profiles/catalog.json').read_text())['monsters']:
        pairs.update((f,entry['monster']) for f in entry['fields'] if f in fields)
    pairs=sorted(pairs)
    donor={m:d for d,models in FAMILIES.items() for m in models}
    endgame={5,14,20,34,88,89,66,64,186,84,92,93,15,63,94,194,8,98,40,67,21,190,57,38,85,54,52,71,72,73}
    values={}; records=[]
    for model in sorted({m for _,m in pairs}):
        reference=donor.get(model,model if model in endgame else 34)
        p=mod/f'data/mods/ffx_ps2/ffx/master/jppc/battle/mon/_m{reference:03}/m{reference:03}.bin'
        data=p.read_bytes(); offset=struct.unpack_from('<I',data,12)[0]
        hp,mp,overkill,*stats=struct.unpack_from('<3I8B',data,offset+20)
        if struct.unpack_from('<H',data,offset+0x72)[0]!=reference or not 0<hp<0x80000000:
            raise ValueError('Reference monster identity or HP domain mismatch')
        values[model]=(hp,overkill,stats)
        records.append(dict(monster=model,reference=reference,path=str(p.relative_to(mod)),sha256=hashlib.sha256(data).hexdigest(),hp=hp,overkill=overkill,stats=stats))
    lines=['// Jarvis-HOOK. Generated by tools/capture_cascade/author_scaling.py. RAM only.', '#pragma once', '#include <cstdint>', 'namespace FfxHooks::CaptureCascade::Scaling {', 'struct Floor {unsigned field,monster; std::uint32_t hp,overkill; std::uint8_t stats[8];};', 'inline constexpr Floor floors[] = {']
    for field,model in pairs:
        hp,overkill,stats=values[model]
        lines.append(f'    {{{field},{model},{hp},{overkill},{{'+','.join(map(str,stats))+'}},')
    lines+=['};','inline const Floor* Find(unsigned field,unsigned monster) noexcept {for(const auto& f:floors)if(f.field==field&&f.monster==monster)return &f;return nullptr;}','}']
    output.write_text('\n'.join(lines)+'\n')
    evidence.write_text(json.dumps(dict(author='Jarvis-HOOK',policy='Runtime only, awakened natural region, component-wise maximum before T7, preserve MP and original files',references=records),indent=2)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--mod',type=Path,required=True);a=p.parse_args()
    generate(a.mod,a.mod/'docs/CAPTURE_CASCADE_ASSETS_2026-10-09.json',ROOT/'src/runtime/FfxHooksDll/hooks/CaptureCascadeScaling.generated.h',a.mod/'docs/CAPTURE_CASCADE_SCALING_2026-10-09.json')
